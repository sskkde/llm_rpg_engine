"""Asset usage tracking service for cost monitoring and analytics.

Provides cost recording, aggregation, and retrieval for asset generation.
Never raises exceptions to callers — always returns response objects.
"""

import logging
import uuid
from datetime import datetime
from typing import Any, Dict, List, Optional

from llm_rpg.storage.repositories import (
    AssetUsageLogRepository,
    AssetJobRepository,
    AssetRepository,
)

logger = logging.getLogger(__name__)


class AssetUsageService:
    """Service for tracking and querying asset generation costs.

    Records usage logs on job creation and completion.
    Provides aggregated cost summaries and filtered queries.
    Never raises exceptions to callers.
    """

    def __init__(
        self,
        usage_log_repository: Optional[AssetUsageLogRepository] = None,
        asset_job_repository: Optional[AssetJobRepository] = None,
        asset_repository: Optional[AssetRepository] = None,
    ):
        """Initialize the service with optional repositories.

        Args:
            usage_log_repository: Repository for usage logs.
            asset_job_repository: Repository for job records.
            asset_repository: Repository for asset records.
        """
        self._usage_repo = usage_log_repository
        self._job_repo = asset_job_repository
        self._asset_repo = asset_repository

    def record_usage(
        self,
        job_id: Optional[str] = None,
        provider_name: Optional[str] = None,
        operation: Optional[str] = None,
        estimated_cost: Optional[float] = None,
        actual_cost: Optional[float] = None,
        session_id: Optional[str] = None,
        user_id: Optional[str] = None,
        asset_id: Optional[str] = None,
        asset_type: Optional[str] = None,
        input_units: Optional[float] = None,
        output_units: Optional[float] = None,
        status: Optional[str] = None,
        metadata: Optional[Dict[str, Any]] = None,
    ) -> Optional[Dict[str, Any]]:
        """Record a usage log entry for an asset generation job.

        Creates an AssetUsageLogModel entry with the provided data.
        If job_id is provided, looks up job details for enrichment.

        Args:
            job_id: The job ID this usage is for.
            provider_name: The provider name (e.g., 'mock', 'openai_image').
            operation: The operation type (e.g., 'generate', 'retry').
            estimated_cost: Estimated cost in USD.
            actual_cost: Actual cost in USD.
            session_id: Session ID for scoping.
            user_id: User ID for attribution.
            asset_id: Asset ID if generated.
            asset_type: Asset type (portrait, scene, bgm).
            input_units: Input units (e.g., prompt tokens).
            output_units: Output units (e.g., generated bytes).
            status: Status of the usage record.
            metadata: Additional metadata dict.

        Returns:
            Dict with usage_id and created_at, or None on error.
        """
        if self._usage_repo is None:
            logger.warning("AssetUsageService.record_usage called without usage_repo")
            return None

        # Enrich from job if job_id provided and repos available
        if job_id and self._job_repo is not None:
            job = self._job_repo.get_by_job_id(job_id)
            if job is not None:
                if provider_name is None:
                    provider_name = job.provider_name
                if session_id is None:
                    session_id = job.session_id
                if asset_type is None:
                    asset_type = job.asset_type
                if asset_id is None:
                    asset_id = job.asset_id
                # Use job's cost fields if not provided
                if estimated_cost is None and job.estimated_cost_usd is not None:
                    estimated_cost = job.estimated_cost_usd
                if actual_cost is None and job.actual_cost_usd is not None:
                    actual_cost = job.actual_cost_usd

        usage_id = str(uuid.uuid4())
        now = datetime.now()

        data = {
            "id": str(uuid.uuid4()),
            "usage_id": usage_id,
            "job_id": job_id,
            "asset_id": asset_id,
            "session_id": session_id,
            "user_id": user_id,
            "provider_name": provider_name,
            "asset_type": asset_type,
            "operation": operation,
            "input_units": input_units,
            "output_units": output_units,
            "estimated_cost_usd": estimated_cost,
            "actual_cost_usd": actual_cost,
            "currency": "USD",
            "status": status,
            "metadata_json": metadata or {},
            "created_at": now,
        }

        try:
            log = self._usage_repo.create_usage_log(data)
            return {
                "usage_id": log.usage_id,
                "created_at": log.created_at.isoformat() if log.created_at else now.isoformat(),
            }
        except Exception as exc:
            logger.warning("Failed to record usage for job %s: %s", job_id, exc)
            return None

    def get_session_usage(
        self, session_id: str, limit: int = 50, offset: int = 0
    ) -> List[Dict[str, Any]]:
        """Get usage logs for a specific session.

        Args:
            session_id: Session ID to filter by.
            limit: Maximum number of records to return.
            offset: Number of records to skip.

        Returns:
            List of usage log dicts, empty list on error.
        """
        if self._usage_repo is None:
            return []

        try:
            logs = self._usage_repo.list_by_session(session_id, limit=limit, offset=offset)
            return [self._map_log_to_dict(log) for log in logs]
        except Exception as exc:
            logger.warning("Failed to get session usage for %s: %s", session_id, exc)
            return []

    def get_user_usage(
        self, user_id: str, limit: int = 50, offset: int = 0
    ) -> List[Dict[str, Any]]:
        """Get usage logs for a specific user.

        Args:
            user_id: User ID to filter by.
            limit: Maximum number of records to return.
            offset: Number of records to skip.

        Returns:
            List of usage log dicts, empty list on error.
        """
        if self._usage_repo is None:
            return []

        try:
            logs = self._usage_repo.list_by_user(user_id, limit=limit, offset=offset)
            return [self._map_log_to_dict(log) for log in logs]
        except Exception as exc:
            logger.warning("Failed to get user usage for %s: %s", user_id, exc)
            return []

    def get_provider_usage(
        self, provider_name: str, limit: int = 50, offset: int = 0
    ) -> List[Dict[str, Any]]:
        """Get usage logs for a specific provider.

        Args:
            provider_name: Provider name to filter by.
            limit: Maximum number of records to return.
            offset: Number of records to skip.

        Returns:
            List of usage log dicts, empty list on error.
        """
        if self._usage_repo is None:
            return []

        try:
            logs = self._usage_repo.list_by_provider(provider_name, limit=limit, offset=offset)
            return [self._map_log_to_dict(log) for log in logs]
        except Exception as exc:
            logger.warning("Failed to get provider usage for %s: %s", provider_name, exc)
            return []

    def get_cost_summary(
        self,
        session_id: Optional[str] = None,
        user_id: Optional[str] = None,
        provider_name: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Get aggregated cost summary for matching usage logs.

        Args:
            session_id: Optional session ID filter.
            user_id: Optional user ID filter.
            provider_name: Optional provider name filter.

        Returns:
            Dict with total_estimated, total_actual, and count.
            Returns zeros on error.
        """
        if self._usage_repo is None:
            return {"total_estimated": 0.0, "total_actual": 0.0, "count": 0}

        try:
            return self._usage_repo.get_cost_summary(
                session_id=session_id,
                user_id=user_id,
                provider_name=provider_name,
            )
        except Exception as exc:
            logger.warning("Failed to get cost summary: %s", exc)
            return {"total_estimated": 0.0, "total_actual": 0.0, "count": 0}

    def list_all_usage(
        self,
        limit: int = 50,
        offset: int = 0,
        session_id: Optional[str] = None,
        user_id: Optional[str] = None,
        provider_name: Optional[str] = None,
    ) -> Dict[str, Any]:
        """List all usage logs with optional filtering.

        Args:
            limit: Maximum number of records to return.
            offset: Number of records to skip.
            session_id: Optional session ID filter.
            user_id: Optional user ID filter.
            provider_name: Optional provider name filter.

        Returns:
            Dict with 'total' and 'items' keys.
        """
        if self._usage_repo is None:
            return {"total": 0, "items": []}

        try:
            # Build query with filters
            from sqlalchemy import desc
            from llm_rpg.storage.models import AssetUsageLogModel

            query = self._usage_repo.db.query(AssetUsageLogModel)

            if session_id is not None:
                query = query.filter(AssetUsageLogModel.session_id == session_id)
            if user_id is not None:
                query = query.filter(AssetUsageLogModel.user_id == user_id)
            if provider_name is not None:
                query = query.filter(AssetUsageLogModel.provider_name == provider_name)

            # Get total count
            total = query.count()

            # Get paginated results
            logs = (
                query.order_by(desc(AssetUsageLogModel.created_at))
                .offset(offset)
                .limit(limit)
                .all()
            )

            return {
                "total": total,
                "items": [self._map_log_to_dict(log) for log in logs],
            }
        except Exception as exc:
            logger.warning("Failed to list all usage: %s", exc)
            return {"total": 0, "items": []}

    @staticmethod
    def _map_log_to_dict(log) -> Dict[str, Any]:
        """Map an AssetUsageLogModel to a dict for API response."""
        return {
            "usage_id": log.usage_id,
            "job_id": log.job_id,
            "asset_id": log.asset_id,
            "session_id": log.session_id,
            "user_id": log.user_id,
            "provider_name": log.provider_name,
            "asset_type": log.asset_type,
            "operation": log.operation,
            "input_units": log.input_units,
            "output_units": log.output_units,
            "estimated_cost_usd": log.estimated_cost_usd,
            "actual_cost_usd": log.actual_cost_usd,
            "currency": log.currency,
            "status": log.status,
            "metadata": log.metadata_json or {},
            "created_at": log.created_at.isoformat() if log.created_at else None,
        }
